CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    email TEXT NOT NULL,
    estado TEXT NOT NULL CHECK (estado IN ('activo', 'prospecto', 'inactivo')),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS clientes_email_idx ON clientes (email);
CREATE INDEX IF NOT EXISTS clientes_estado_idx ON clientes (estado, id);

CREATE TABLE IF NOT EXISTS contactos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes (id) ON DELETE CASCADE,
    nombre TEXT NOT NULL,
    email TEXT NOT NULL,
    cargo TEXT NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS contactos_cliente_idx ON contactos (cliente_id, id);
CREATE INDEX IF NOT EXISTS contactos_email_idx ON contactos (email);

CREATE TABLE IF NOT EXISTS oportunidades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes (id) ON DELETE CASCADE,
    nombre TEXT NOT NULL,
    monto NUMERIC(14, 2) NOT NULL CHECK (monto >= 0),
    estado TEXT NOT NULL CHECK (estado IN ('abierta', 'ganada', 'perdida')),
    cierre_estimado DATE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS oportunidades_cliente_idx ON oportunidades (cliente_id, id);
CREATE INDEX IF NOT EXISTS oportunidades_estado_idx
    ON oportunidades (estado, cierre_estimado, cliente_id);

CREATE TABLE IF NOT EXISTS actividades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes (id) ON DELETE CASCADE,
    tipo TEXT NOT NULL CHECK (tipo IN ('llamada', 'email', 'reunion')),
    descripcion TEXT NOT NULL,
    ocurrio_en TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS actividades_cliente_idx
    ON actividades (cliente_id, ocurrio_en DESC, id);
